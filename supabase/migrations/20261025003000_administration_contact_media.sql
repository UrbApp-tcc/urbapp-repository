-- Anexos privados e opcionais para contatos institucionais.

alter table public.administration_contact_requests
  add column if not exists notified_at timestamptz;

update public.administration_contact_requests
set notified_at = created_at
where notified_at is null;

create table if not exists public.administration_contact_request_media (
  id bigint generated by default as identity primary key,
  request_id bigint not null references public.administration_contact_requests(id) on delete cascade,
  storage_path text not null unique,
  file_name text not null,
  media_type text not null,
  mime_type text not null,
  size_bytes bigint not null,
  position smallint not null,
  created_at timestamptz not null default now(),
  constraint administration_contact_media_type_check
    check (media_type in ('image', 'video')),
  constraint administration_contact_media_size_check
    check (size_bytes > 0 and size_bytes <= 52428800),
  constraint administration_contact_media_position_check
    check (position between 1 and 5),
  unique (request_id, position)
);

create index if not exists administration_contact_media_request_idx
  on public.administration_contact_request_media (request_id, position);

alter table public.administration_contact_request_media enable row level security;
revoke all on public.administration_contact_request_media from public, anon, authenticated;
grant select, insert on public.administration_contact_request_media to authenticated;
grant all on public.administration_contact_request_media to service_role;

drop policy if exists "Contact participants view request media"
  on public.administration_contact_request_media;
create policy "Contact participants view request media"
on public.administration_contact_request_media for select to authenticated
using (
  exists (
    select 1
    from public.administration_contact_requests request
    where request.id = request_id
      and (
        request.requester_user_id = auth.uid()
        or exists (
          select 1
          from public.platform_user_roles role
          where role.user_id = auth.uid()
            and role.role in ('admin', 'moderator')
        )
      )
  )
);

drop policy if exists "Requesters attach media before notification"
  on public.administration_contact_request_media;
create policy "Requesters attach media before notification"
on public.administration_contact_request_media for insert to authenticated
with check (
  storage_path like auth.uid()::text || '/' || request_id::text || '/%'
  and exists (
    select 1
    from public.administration_contact_requests request
    where request.id = request_id
      and request.requester_user_id = auth.uid()
      and request.notified_at is null
  )
  and exists (
    select 1
    from storage.objects object
    where object.bucket_id = 'administration-contact-media'
      and object.name = storage_path
      and (object.owner = auth.uid() or object.owner_id = auth.uid()::text)
  )
);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'administration-contact-media',
  'administration-contact-media',
  false,
  52428800,
  array[
    'image/jpeg', 'image/png', 'image/webp', 'image/gif',
    'video/mp4', 'video/quicktime', 'video/webm'
  ]
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Institutional contacts upload own media" on storage.objects;
create policy "Institutional contacts upload own media"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'administration-contact-media'
  and (storage.foldername(name))[1] = auth.uid()::text
);

drop policy if exists "Contact participants view private media" on storage.objects;
create policy "Contact participants view private media"
on storage.objects for select to authenticated
using (
  bucket_id = 'administration-contact-media'
  and (
    owner = auth.uid()
    or owner_id = auth.uid()::text
    or exists (
      select 1
      from public.platform_user_roles role
      where role.user_id = auth.uid()
        and role.role in ('admin', 'moderator')
    )
  )
);

drop policy if exists "Institutional contacts remove own media" on storage.objects;
create policy "Institutional contacts remove own media"
on storage.objects for delete to authenticated
using (
  bucket_id = 'administration-contact-media'
  and (owner = auth.uid() or owner_id = auth.uid()::text)
);

create or replace function public.create_administration_contact_request(
  target_administration_id bigint,
  contact_kind text,
  contact_subject text,
  contact_message text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  kind_is_valid boolean;
  request_id bigint;
begin
  if current_user_id is null then
    raise exception 'Faça login para entrar em contato com a administração do UrbApp.';
  end if;

  if not exists (
    select 1
    from public.administration_users member
    where member.administration_id = target_administration_id
      and member.user_id = current_user_id
      and member.is_active = true
  ) then
    raise exception 'Apenas integrantes ativos da gestão podem enviar este pedido.';
  end if;

  kind_is_valid := contact_kind in (
    'content_contestation',
    'credentialing',
    'profile_creation',
    'profile_update',
    'support_partnership'
  );
  if not kind_is_valid then
    raise exception 'Selecione um tipo de contato válido.';
  end if;
  if char_length(trim(coalesce(contact_subject, ''))) not between 5 and 100 then
    raise exception 'O título deve ter entre 5 e 100 caracteres.';
  end if;
  if char_length(trim(coalesce(contact_message, ''))) not between 20 and 1500 then
    raise exception 'A descrição deve ter entre 20 e 1500 caracteres.';
  end if;

  insert into public.administration_contact_requests (
    administration_id,
    requester_user_id,
    request_kind,
    subject,
    message,
    notified_at
  ) values (
    target_administration_id,
    current_user_id,
    contact_kind,
    trim(contact_subject),
    trim(contact_message),
    null
  ) returning id into request_id;

  return request_id;
end;
$$;

create or replace function public.finalize_administration_contact_request(
  target_request_id bigint
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  target_request public.administration_contact_requests%rowtype;
  target_administration public.municipal_administrations%rowtype;
  requester_profile public.profiles%rowtype;
  requester_badge_name text;
  kind_label text;
  media_count integer;
  sent_count integer;
begin
  select * into strict target_request
  from public.administration_contact_requests request
  where request.id = target_request_id
  for update;

  if current_user_id is null or target_request.requester_user_id <> current_user_id then
    raise exception 'Você não pode finalizar este pedido.';
  end if;
  if target_request.notified_at is not null then
    raise exception 'Este pedido já foi enviado aos administradores.';
  end if;

  kind_label := case target_request.request_kind
    when 'content_contestation' then 'Contestação de publicação'
    when 'credentialing' then 'Credenciamento institucional'
    when 'profile_creation' then 'Criação de perfil institucional'
    when 'profile_update' then 'Atualização de perfil institucional'
    when 'support_partnership' then 'Suporte ou parceria'
  end;

  select * into strict target_administration
  from public.municipal_administrations administration
  where administration.id = target_request.administration_id;

  select * into strict requester_profile
  from public.profiles profile
  where profile.id = current_user_id;

  select badge.name into requester_badge_name
  from public.badges badge
  where badge.id = requester_profile.featured_badge_id;

  select count(*)::integer into media_count
  from public.administration_contact_request_media media
  where media.request_id = target_request_id;

  insert into public.notifications (user_id, type, title, body, payload)
  select
    role.user_id,
    'administration_contact',
    target_request.subject,
    target_request.message,
    jsonb_build_object(
      'request_id', target_request.id,
      'contact_kind', target_request.request_kind,
      'contact_kind_label', kind_label,
      'administration_id', target_request.administration_id,
      'administration_name', target_administration.name,
      'requester_user_id', current_user_id,
      'requester_name', requester_profile.full_name,
      'requester_username', requester_profile.username,
      'requester_badge_name', requester_badge_name,
      'requester_level', requester_profile.current_level,
      'request_subject', target_request.subject,
      'request_message', target_request.message,
      'media_count', media_count
    )
  from public.platform_user_roles role
  where role.role = 'admin';

  get diagnostics sent_count = row_count;
  if sent_count = 0 then
    raise exception 'Nenhum administrador está disponível para receber o pedido.';
  end if;

  update public.administration_contact_requests
  set notified_at = now()
  where id = target_request_id;

  return sent_count;
end;
$$;

create or replace function public.cancel_administration_contact_request(
  target_request_id bigint
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.administration_contact_requests request
  where request.id = target_request_id
    and request.requester_user_id = auth.uid()
    and request.notified_at is null;
end;
$$;

revoke all on function public.finalize_administration_contact_request(bigint)
  from public, anon;
grant execute on function public.finalize_administration_contact_request(bigint)
  to authenticated;

revoke all on function public.cancel_administration_contact_request(bigint)
  from public, anon;
grant execute on function public.cancel_administration_contact_request(bigint)
  to authenticated;
