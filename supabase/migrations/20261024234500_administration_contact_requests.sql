-- Canal inicial de contato entre gestões municipais e administradores do UrbApp.
-- O pedido fica auditável e sua entrada operacional é a central de notificações.

create table if not exists public.administration_contact_requests (
  id bigint generated by default as identity primary key,
  administration_id bigint not null references public.municipal_administrations(id) on delete restrict,
  requester_user_id uuid not null references public.profiles(id) on delete restrict,
  request_kind text not null,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now(),
  constraint administration_contact_requests_kind_check check (
    request_kind in (
      'content_contestation',
      'credentialing',
      'profile_creation',
      'profile_update',
      'support_partnership'
    )
  ),
  constraint administration_contact_requests_subject_check
    check (char_length(trim(subject)) between 5 and 100),
  constraint administration_contact_requests_message_check
    check (char_length(trim(message)) between 20 and 1500)
);

create index if not exists administration_contact_requests_created_idx
  on public.administration_contact_requests (created_at desc);

alter table public.administration_contact_requests enable row level security;
revoke all on public.administration_contact_requests from public, anon, authenticated;
grant select on public.administration_contact_requests to authenticated;
grant all on public.administration_contact_requests to service_role;

drop policy if exists "Institutional requesters view own contacts"
  on public.administration_contact_requests;
create policy "Institutional requesters view own contacts"
on public.administration_contact_requests for select to authenticated
using (requester_user_id = auth.uid());

drop policy if exists "Platform administrators view institutional contacts"
  on public.administration_contact_requests;
create policy "Platform administrators view institutional contacts"
on public.administration_contact_requests for select to authenticated
using (
  exists (
    select 1
    from public.platform_user_roles role
    where role.user_id = auth.uid()
      and role.role in ('admin', 'moderator')
  )
);

create or replace function public.create_administration_contact_request(
  target_administration_id bigint,
  contact_kind text,
  contact_subject text,
  contact_message text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  target_administration public.municipal_administrations%rowtype;
  requester_profile public.profiles%rowtype;
  requester_badge_name text;
  kind_label text;
  request_id bigint;
  sent_count integer;
begin
  if current_user_id is null then
    raise exception 'Faça login para entrar em contato com a administração do UrbApp.';
  end if;

  if not exists (
    select 1
    from public.administration_users member
    where member.administration_id = target_administration_id
      and member.user_id = current_user_id
      and member.is_active = true
  ) then
    raise exception 'Apenas integrantes ativos da gestão podem enviar este pedido.';
  end if;

  kind_label := case contact_kind
    when 'content_contestation' then 'Contestação de publicação'
    when 'credentialing' then 'Credenciamento institucional'
    when 'profile_creation' then 'Criação de perfil institucional'
    when 'profile_update' then 'Atualização de perfil institucional'
    when 'support_partnership' then 'Suporte ou parceria'
    else null
  end;

  if kind_label is null then
    raise exception 'Selecione um tipo de contato válido.';
  end if;
  if char_length(trim(coalesce(contact_subject, ''))) not between 5 and 100 then
    raise exception 'O título deve ter entre 5 e 100 caracteres.';
  end if;
  if char_length(trim(coalesce(contact_message, ''))) not between 20 and 1500 then
    raise exception 'A descrição deve ter entre 20 e 1500 caracteres.';
  end if;

  select * into strict target_administration
  from public.municipal_administrations administration
  where administration.id = target_administration_id;

  select * into strict requester_profile
  from public.profiles profile
  where profile.id = current_user_id;

  select badge.name into requester_badge_name
  from public.badges badge
  where badge.id = requester_profile.featured_badge_id;

  insert into public.administration_contact_requests (
    administration_id,
    requester_user_id,
    request_kind,
    subject,
    message
  ) values (
    target_administration_id,
    current_user_id,
    contact_kind,
    trim(contact_subject),
    trim(contact_message)
  ) returning id into request_id;

  insert into public.notifications (user_id, type, title, body, payload)
  select
    role.user_id,
    'administration_contact',
    trim(contact_subject),
    trim(contact_message),
    jsonb_build_object(
      'request_id', request_id,
      'contact_kind', contact_kind,
      'contact_kind_label', kind_label,
      'administration_id', target_administration_id,
      'administration_name', target_administration.name,
      'requester_user_id', current_user_id,
      'requester_name', requester_profile.full_name,
      'requester_username', requester_profile.username,
      'requester_badge_name', requester_badge_name,
      'requester_level', requester_profile.current_level,
      'request_subject', trim(contact_subject),
      'request_message', trim(contact_message)
    )
  from public.platform_user_roles role
  where role.role = 'admin';

  get diagnostics sent_count = row_count;
  if sent_count = 0 then
    raise exception 'Nenhum administrador está disponível para receber o pedido.';
  end if;

  return request_id;
end;
$$;

revoke all on function public.create_administration_contact_request(bigint, text, text, text)
  from public, anon;
grant execute on function public.create_administration_contact_request(bigint, text, text, text)
  to authenticated;
