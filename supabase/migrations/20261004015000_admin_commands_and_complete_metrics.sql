create table if not exists public.validation_settings_history (
  id bigint generated by default as identity primary key,
  settings_id bigint references public.validation_settings(id) on delete set null,
  city_id bigint references public.cities(id) on delete set null,
  confirmations_required integer not null,
  rejections_required integer not null,
  radius_km numeric(8,3) not null,
  cycle_duration interval not null,
  initiator_cooldown interval not null,
  changed_by uuid references public.profiles(id) on delete set null,
  effective_at timestamptz not null default now()
);

alter table public.validation_settings_history enable row level security;
grant select on public.validation_settings_history to authenticated;
grant all on public.validation_settings_history to service_role;

create policy "Validation configuration history is public to users"
on public.validation_settings_history
for select to authenticated
using (true);

insert into public.validation_settings_history (
  settings_id,
  city_id,
  confirmations_required,
  rejections_required,
  radius_km,
  cycle_duration,
  initiator_cooldown,
  effective_at
)
select
  settings.id,
  settings.city_id,
  settings.confirmations_required,
  settings.rejections_required,
  settings.radius_km,
  settings.cycle_duration,
  settings.initiator_cooldown,
  settings.created_at
from public.validation_settings settings
where not exists (
  select 1
  from public.validation_settings_history history
  where history.settings_id = settings.id
);

create or replace function public.configure_validation_settings(
  target_city_id bigint,
  required_confirmations integer,
  required_rejections integer,
  maximum_radius_km numeric,
  duration_hours integer,
  cooldown_hours integer
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  resolved_settings_id bigint;
begin
  if not public.is_platform_admin(current_user_id) then
    raise exception 'Apenas administradores podem alterar a validacao.' using errcode = '42501';
  end if;

  if required_confirmations < 1
     or required_rejections < 1
     or maximum_radius_km <= 0
     or duration_hours < 1
     or cooldown_hours < 0 then
    raise exception 'Parametros de validacao invalidos.';
  end if;

  if target_city_id is null or not exists (
    select 1 from public.cities city where city.id = target_city_id
  ) then
    raise exception 'Cidade invalida.';
  end if;

  insert into public.validation_settings (
    city_id,
    confirmations_required,
    rejections_required,
    radius_km,
    cycle_duration,
    initiator_cooldown
  )
  values (
    target_city_id,
    required_confirmations,
    required_rejections,
    maximum_radius_km,
    make_interval(hours => duration_hours),
    make_interval(hours => cooldown_hours)
  )
  on conflict (city_id) where city_id is not null do update
    set confirmations_required = excluded.confirmations_required,
        rejections_required = excluded.rejections_required,
        radius_km = excluded.radius_km,
        cycle_duration = excluded.cycle_duration,
        initiator_cooldown = excluded.initiator_cooldown,
        updated_at = now()
  returning id into resolved_settings_id;

  insert into public.validation_settings_history (
    settings_id,
    city_id,
    confirmations_required,
    rejections_required,
    radius_km,
    cycle_duration,
    initiator_cooldown,
    changed_by
  )
  values (
    resolved_settings_id,
    target_city_id,
    required_confirmations,
    required_rejections,
    maximum_radius_km,
    make_interval(hours => duration_hours),
    make_interval(hours => cooldown_hours),
    current_user_id
  );

  return resolved_settings_id;
end;
$$;

create or replace function public.configure_agency_responsibility(
  target_city_id bigint,
  target_category_id bigint,
  target_agency_id bigint,
  change_reason text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  created_responsibility_id bigint;
begin
  if not public.is_platform_admin(current_user_id)
     and not exists (
       select 1
       from public.administration_users member
       join public.municipal_administrations administration
         on administration.id = member.administration_id
       where member.user_id = current_user_id
         and member.is_active = true
         and member.role = 'manager'
         and administration.city_id = target_city_id
         and administration.ends_on is null
     ) then
    raise exception 'Usuario sem permissao para configurar responsabilidades.' using errcode = '42501';
  end if;

  if char_length(trim(coalesce(change_reason, ''))) < 3 then
    raise exception 'Informe o motivo da alteracao.';
  end if;

  if not exists (
    select 1 from public.public_agencies agency
    where agency.id = target_agency_id and agency.city_id = target_city_id
  ) then
    raise exception 'O orgao deve pertencer a cidade informada.';
  end if;

  update public.agency_responsibilities
  set ends_on = current_date
  where city_id = target_city_id
    and category_id = target_category_id
    and ends_on is null;

  insert into public.agency_responsibilities (
    city_id,
    category_id,
    agency_id,
    starts_on,
    created_by,
    reason
  )
  values (
    target_city_id,
    target_category_id,
    target_agency_id,
    current_date,
    current_user_id,
    trim(change_reason)
  )
  returning id into created_responsibility_id;

  return created_responsibility_id;
end;
$$;

create or replace function public.upsert_problem_category(
  target_category_id bigint,
  category_name text,
  category_slug text,
  category_description text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  resolved_category_id bigint;
begin
  if not public.is_platform_admin(current_user_id) then
    raise exception 'Apenas administradores podem configurar categorias.' using errcode = '42501';
  end if;

  if char_length(trim(coalesce(category_name, ''))) < 2
     or trim(coalesce(category_slug, '')) !~ '^[a-z0-9]+(?:-[a-z0-9]+)*$' then
    raise exception 'Nome ou identificador de categoria invalido.';
  end if;

  if target_category_id is null then
    insert into public.problem_categories (name, slug, description)
    values (
      trim(category_name),
      lower(trim(category_slug)),
      nullif(trim(coalesce(category_description, '')), '')
    )
    returning id into resolved_category_id;
  else
    update public.problem_categories
    set name = trim(category_name),
        slug = lower(trim(category_slug)),
        description = nullif(trim(coalesce(category_description, '')), '')
    where id = target_category_id
    returning id into resolved_category_id;

    if resolved_category_id is null then
      raise exception 'Categoria nao encontrada.';
    end if;
  end if;

  return resolved_category_id;
end;
$$;

create or replace function public.set_occurrence_jurisdiction(
  target_occurrence_id bigint,
  jurisdiction text,
  external_responsible text,
  change_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  target_occurrence public.occurrences%rowtype;
begin
  if jurisdiction not in ('municipal', 'state', 'federal', 'concessionaire', 'private', 'unknown') then
    raise exception 'Competencia invalida.';
  end if;

  if char_length(trim(coalesce(change_reason, ''))) < 3 then
    raise exception 'Informe a justificativa da classificacao.';
  end if;

  select * into target_occurrence
  from public.occurrences occurrence
  where occurrence.id = target_occurrence_id
  for update;

  if not found then
    raise exception 'Ocorrencia nao encontrada.';
  end if;

  if not public.is_platform_admin(current_user_id)
     and not exists (
       select 1 from public.administration_users member
       where member.administration_id = target_occurrence.administration_id
         and member.user_id = current_user_id
         and member.is_active = true
     ) then
    raise exception 'Usuario sem permissao para classificar competencia.' using errcode = '42501';
  end if;

  update public.occurrences
  set jurisdiction_type = jurisdiction,
      external_responsible_name = nullif(trim(coalesce(external_responsible, '')), ''),
      updated_at = now()
  where id = target_occurrence.id;

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata
  )
  values (
    target_occurrence.id,
    current_user_id,
    case when public.is_platform_admin(current_user_id) then 'moderator' else 'administration' end,
    'jurisdiction_changed',
    trim(change_reason),
    target_occurrence.administration_id,
    target_occurrence.agency_id,
    jsonb_build_object(
      'previous_jurisdiction', target_occurrence.jurisdiction_type,
      'jurisdiction', jurisdiction,
      'external_responsible', nullif(trim(coalesce(external_responsible, '')), '')
    )
  );
end;
$$;

create or replace function public.merge_duplicate_occurrences(
  primary_occurrence_id bigint,
  duplicate_occurrence_id bigint,
  merge_reason text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  primary_occurrence public.occurrences%rowtype;
  duplicate_occurrence public.occurrences%rowtype;
  moved_report record;
begin
  if not public.is_platform_admin(current_user_id) then
    raise exception 'Apenas a moderacao pode consolidar duplicidades.' using errcode = '42501';
  end if;

  if primary_occurrence_id = duplicate_occurrence_id then
    raise exception 'Selecione duas ocorrencias diferentes.';
  end if;

  if char_length(trim(coalesce(merge_reason, ''))) < 3 then
    raise exception 'Informe o motivo da consolidacao.';
  end if;

  select * into primary_occurrence
  from public.occurrences occurrence
  where occurrence.id = primary_occurrence_id
    and occurrence.invalidated_at is null
  for update;

  select * into duplicate_occurrence
  from public.occurrences occurrence
  where occurrence.id = duplicate_occurrence_id
    and occurrence.invalidated_at is null
  for update;

  if primary_occurrence.id is null or duplicate_occurrence.id is null then
    raise exception 'Ocorrencia principal ou duplicada nao encontrada.';
  end if;

  if primary_occurrence.city_id <> duplicate_occurrence.city_id then
    raise exception 'Ocorrencias de cidades diferentes nao podem ser consolidadas.';
  end if;

  update public.resolution_cycles
  set status = 'cancelled', closed_at = now()
  where occurrence_id = duplicate_occurrence.id
    and status = 'pending';

  for moved_report in
    select post.id, post.status
    from public.posts post
    where post.occurrence_id = duplicate_occurrence.id
    for update
  loop
    insert into public.post_status_history (
      post_id,
      changed_by,
      from_status,
      to_status,
      note
    )
    values (
      moved_report.id,
      current_user_id,
      moved_report.status,
      primary_occurrence.status,
      'Relato associado a ocorrencia principal apos consolidacao de duplicidade.'
    );
  end loop;

  update public.posts
  set occurrence_id = primary_occurrence.id,
      city_id = primary_occurrence.city_id,
      category_id = primary_occurrence.category_id,
      agency_id = primary_occurrence.agency_id,
      status = primary_occurrence.status,
      resolved_at = primary_occurrence.resolved_at,
      updated_at = now()
  where occurrence_id = duplicate_occurrence.id;

  update public.occurrence_agency_assignments
  set ends_at = coalesce(ends_at, now())
  where occurrence_id = duplicate_occurrence.id
    and ends_at is null;

  update public.occurrences
  set status = 'closed',
      resolved_at = null,
      invalidated_at = now(),
      merged_into_occurrence_id = primary_occurrence.id,
      closed_reason = 'duplicate_merged',
      invalidation_reason = trim(merge_reason),
      updated_at = now()
  where id = duplicate_occurrence.id;

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata
  )
  values
    (
      primary_occurrence.id,
      current_user_id,
      'moderator',
      'duplicate_absorbed',
      trim(merge_reason),
      primary_occurrence.administration_id,
      primary_occurrence.agency_id,
      jsonb_build_object('absorbed_occurrence_id', duplicate_occurrence.id)
    ),
    (
      duplicate_occurrence.id,
      current_user_id,
      'moderator',
      'occurrence_merged',
      trim(merge_reason),
      duplicate_occurrence.administration_id,
      duplicate_occurrence.agency_id,
      jsonb_build_object('primary_occurrence_id', primary_occurrence.id)
    );
end;
$$;

-- Métricas públicas contam ocorrências únicas, municipais e não invalidadas.
create or replace view public.city_occurrence_metrics
with (security_invoker = true)
as
select
  city.id as city_id,
  city.name as city_name,
  count(occurrence.id) filter (
    where occurrence.invalidated_at is null and occurrence.jurisdiction_type = 'municipal'
  ) as total_occurrences,
  count(occurrence.id) filter (
    where occurrence.status = 'completed' and occurrence.invalidated_at is null
      and occurrence.jurisdiction_type = 'municipal'
  ) as resolved_occurrences,
  count(occurrence.id) filter (
    where occurrence.status = 'open' and occurrence.invalidated_at is null
      and occurrence.jurisdiction_type = 'municipal'
  ) as open_occurrences,
  count(occurrence.id) filter (
    where occurrence.status in ('in_analysis', 'in_progress', 'reopened')
      and occurrence.invalidated_at is null and occurrence.jurisdiction_type = 'municipal'
  ) as active_occurrences,
  count(occurrence.id) filter (
    where occurrence.status = 'awaiting_validation' and occurrence.invalidated_at is null
      and occurrence.jurisdiction_type = 'municipal'
  ) as awaiting_validation_occurrences,
  round(
    100.0 * count(occurrence.id) filter (
      where occurrence.status = 'completed' and occurrence.invalidated_at is null
        and occurrence.jurisdiction_type = 'municipal'
    ) / nullif(count(occurrence.id) filter (
      where occurrence.invalidated_at is null and occurrence.jurisdiction_type = 'municipal'
    ), 0),
    2
  ) as resolution_rate,
  avg(occurrence.resolved_at - occurrence.created_at) filter (
    where occurrence.status = 'completed' and occurrence.invalidated_at is null
      and occurrence.jurisdiction_type = 'municipal'
  ) as average_resolution_time,
  percentile_cont(0.5) within group (
    order by extract(epoch from (occurrence.resolved_at - occurrence.created_at))
  ) filter (
    where occurrence.status = 'completed' and occurrence.invalidated_at is null
      and occurrence.jurisdiction_type = 'municipal'
  ) as median_resolution_seconds,
  count(occurrence.id) filter (
    where occurrence.invalidated_at is null and occurrence.jurisdiction_type <> 'municipal'
  ) as outside_municipal_occurrences
from public.cities city
left join public.occurrences occurrence on occurrence.city_id = city.id
group by city.id;

create or replace view public.city_category_metrics
with (security_invoker = true)
as
select
  occurrence.city_id,
  occurrence.category_id,
  category.name as category_name,
  count(*) as occurrences_count,
  count(*) filter (where occurrence.status = 'completed') as resolved_count
from public.occurrences occurrence
join public.problem_categories category on category.id = occurrence.category_id
where occurrence.invalidated_at is null
  and occurrence.jurisdiction_type = 'municipal'
group by occurrence.city_id, occurrence.category_id, category.name;

create or replace view public.city_neighborhood_metrics
with (security_invoker = true)
as
select
  occurrence.city_id,
  coalesce(nullif(trim(occurrence.neighborhood), ''), 'Nao informado') as neighborhood,
  count(*) as occurrences_count,
  count(*) filter (where occurrence.status = 'completed') as resolved_count
from public.occurrences occurrence
where occurrence.invalidated_at is null
  and occurrence.jurisdiction_type = 'municipal'
group by occurrence.city_id, coalesce(nullif(trim(occurrence.neighborhood), ''), 'Nao informado');

create or replace view public.city_monthly_metrics
with (security_invoker = true)
as
select
  occurrence.city_id,
  date_trunc('month', occurrence.created_at)::date as month,
  count(*) as registered_count,
  count(*) filter (where occurrence.status = 'completed') as resolved_count
from public.occurrences occurrence
where occurrence.invalidated_at is null
  and occurrence.jurisdiction_type = 'municipal'
group by occurrence.city_id, date_trunc('month', occurrence.created_at)::date;

grant select on public.city_category_metrics to anon, authenticated;
grant select on public.city_neighborhood_metrics to anon, authenticated;
grant select on public.city_monthly_metrics to anon, authenticated;

create or replace function public.notify_post_support_received()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_post public.posts%rowtype;
begin
  select * into target_post
  from public.posts post
  where post.id = new.post_id;

  if target_post.user_id is not null
     and target_post.user_id is distinct from new.user_id
     and target_post.hidden_at is null then
    perform public.notify_user(
      target_post.user_id,
      'post_support',
      'Seu relato recebeu apoio',
      target_post.title,
      jsonb_build_object(
        'post_id', target_post.id,
        'occurrence_id', target_post.occurrence_id,
        'supporter_id', new.user_id
      )
    );
  end if;
  return new;
end;
$$;

drop trigger if exists notify_on_post_support on public.post_supports;
create trigger notify_on_post_support
after insert on public.post_supports
for each row execute function public.notify_post_support_received();

