revoke insert on table public.public_agencies from authenticated;

drop policy if exists "Authenticated users can create public agencies" on public.public_agencies;

revoke execute on function public.create_public_agency_profile(bigint, text, text, text) from authenticated;

create table if not exists public.agency_profile_requests (
  id bigint generated by default as identity primary key,
  requester_user_id uuid not null references public.profiles(id) on delete cascade,
  city_id bigint not null references public.cities(id),
  agency_name text not null,
  agency_type text not null,
  institutional_email text not null,
  requester_role text,
  proof_summary text not null,
  proof_links text,
  review_notes text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null,
  constraint agency_profile_requests_status_check
    check (status in ('pending', 'approved', 'rejected'))
);

create index if not exists agency_profile_requests_requester_idx
  on public.agency_profile_requests (requester_user_id, created_at desc);

grant select, insert on table public.agency_profile_requests to authenticated;
grant all on table public.agency_profile_requests to service_role;

alter table public.agency_profile_requests enable row level security;

drop policy if exists "Users can view their own agency profile requests" on public.agency_profile_requests;
create policy "Users can view their own agency profile requests"
on public.agency_profile_requests
for select
to authenticated
using (auth.uid() = requester_user_id);

drop policy if exists "Users can create their own agency profile requests" on public.agency_profile_requests;
create policy "Users can create their own agency profile requests"
on public.agency_profile_requests
for insert
to authenticated
with check (auth.uid() = requester_user_id);

create or replace function public.create_agency_profile_request(
  target_city_id bigint,
  agency_name text,
  agency_type text,
  institutional_email text,
  requester_role text default null,
  proof_summary text default null,
  proof_links text default null
)
returns public.agency_profile_requests
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  created_request public.agency_profile_requests%rowtype;
begin
  if current_user_id is null then
    raise exception 'Usuário autenticado é obrigatório.';
  end if;

  if target_city_id is null then
    raise exception 'A cidade da solicitação é obrigatória.';
  end if;

  if trim(coalesce(agency_name, '')) = '' then
    raise exception 'O nome da secretaria/órgão é obrigatório.';
  end if;

  if trim(coalesce(agency_type, '')) = '' then
    raise exception 'O tipo da secretaria/órgão é obrigatório.';
  end if;

  if trim(coalesce(institutional_email, '')) = '' then
    raise exception 'O e-mail institucional é obrigatório.';
  end if;

  if trim(coalesce(proof_summary, '')) = '' then
    raise exception 'Descreva as provas institucionais para análise.';
  end if;

  insert into public.agency_profile_requests (
    requester_user_id,
    city_id,
    agency_name,
    agency_type,
    institutional_email,
    requester_role,
    proof_summary,
    proof_links
  )
  values (
    current_user_id,
    target_city_id,
    trim(agency_name),
    trim(agency_type),
    lower(trim(institutional_email)),
    nullif(trim(coalesce(requester_role, '')), ''),
    trim(proof_summary),
    nullif(trim(coalesce(proof_links, '')), '')
  )
  returning * into created_request;

  return created_request;
end;
$$;

grant execute on function public.create_agency_profile_request(bigint, text, text, text, text, text, text) to authenticated;
grant execute on function public.create_agency_profile_request(bigint, text, text, text, text, text, text) to service_role;
