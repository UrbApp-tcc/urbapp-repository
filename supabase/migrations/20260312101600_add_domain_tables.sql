-- criação da tabela categoria de problemas
create table public.problem_categories (
    id bigint generated by default as identity not null,
    name text not null,
    slug text not null,
    description text,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabelas de departamentos/agências/secretarias públicas
create table public.public_agencies (
    id bigint generated by default as identity not null,
    city_id bigint not null references public.cities(id),
    name text not null,
    type text not null,
    contact_email text not null,
    created_at timestamp with time zone not null default now(),
    unique(city_id, name),
    primary key(id)
);

-- criação de tabela de usuários do órgãos públicos
create table public.agency_users (
    id bigint generated by default as identity not null,
    agency_id bigint not null references public.public_agencies(id),
    user_id bigint not null references public.users(id),
    role text not null default 'agent',
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    unique(agency_id, user_id),
    primary key(id)
);

-- criação de tabela de imagem dos posts (1:N)
create table public.post_images (
    id bigint generated by default as identity not null,
    post_id bigint not null references public.posts(id) on delete cascade,
    storage_path text not null,
    caption text,
    position smallint not null default 1,
    created_at timestamp with time zone not null default now(),
    unique(post_id, position),
    primary key(id)
);

-- criação de tabela de apoios/curtidas/likes dos posts
create table public.post_supports (
    id bigint generated by default as identity not null,
    post_id bigint not null references public.posts(id) on delete cascade,
    user_id bigint not null references public.users(id) on delete cascade,
    created_at timestamp with time zone not null default now(),
    unique(post_id, user_id),
    primary key(id)
);

-- criação de tabela de histórico de status dos posts
create table public.post_status_history (
    id bigint generated by default as identity not null,
    post_id bigint not null references public.posts(id) on delete cascade,
    changed_by bigint not null references public.users(id) on delete cascade,
    from_status public.report_status,
    to_status public.report_status not null,
    note text,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabela de notificações
create table public.notifications (
    id bigint generated by default as identity not null,
    user_id bigint not null references public.users(id) on delete cascade,
    type text not null,
    title text not null,
    body text not null,
    payload jsonb,
    read_at timestamptz,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabela de dispositivos de usuários
create table public.user_devices (
    id bigint generated by default as identity not null,
    user_id bigint not null references public.users(id) on delete cascade,
    platform text not null,
    push_token text not null,
    last_seen_at timestamptz,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabelas de badges
create table public.badges (
    id bigint generated by default as identity not null,
    name text not null,
    slug text not null,
    description text not null,
    icon text,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabela de usuários de badges
create table public.user_badges (
    id bigint generated by default as identity not null,
    user_id bigint not null references public.users(id) on delete cascade,
    badge_id bigint not null references public.badges(id) on delete cascade,
    awarded_at timestamptz not null default now(),
    primary key(id)
);

-- criação de tabela de transações de XP
create table public.xp_transactions (
    id bigint generated by default as identity not null,
    user_id bigint not null references public.users(id) on delete cascade,
    source_type text not null,
    source_id bigint,
    xp_delta integer not null default 0,
    points_delta integer not null default 0,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);

-- criação de tabela de reportes de moderação
create table public.moderation_reports (
    id bigint generated by default as identity not null,
    reporter_user_id bigint not null references public.users(id) on delete cascade,
    target_type text not null,
    target_id bigint not null,
    reason text not null,
    status public.report_status not null default 'open',
    created_at timestamp with time zone not null default now(),
    resolved_at timestamptz,
    primary key(id)
);

-- criação de tabela de eventos de atividade do usuário
create table public.activity_events (
    id bigint generated by default as identity not null,
    user_id bigint not null references public.users(id) on delete cascade,
    post_id bigint not null references public.posts(id) on delete cascade,
    event_type text not null,
    metadata jsonb,
    created_at timestamp with time zone not null default now(),
    primary key(id)
);