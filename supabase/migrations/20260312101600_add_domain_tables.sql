-- criação da tabela categoria de problemas
create table public.problem_categories (
    id bigint generated by default as identity not null,
    name text not null,
    slug text not null,
    description text,
    created_at timestamp with time zone not null default now()
);

-- criação de tabelas de departamentos/agências/secretarias públicas
create table public.public_agencies (
    id bigint generated by default as identity not null,
    city_id bigint not null references public.cities(id),
    name text not null,
    type text not null,
    contact_email text not null,
    created_at timestamp with time zone not null default now(),
    unique(city_id, name)
);

-- criação de tabela de usuários do órgãos públicos
create table public.agency_users (
    id bigint generated by default as identity not null,
    agency_id bigint not null references public.public_agencies(id),
    user_id bigint not null references public.users(id),
    role text not null default 'agent',
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    unique(agency_id, user_id)
);