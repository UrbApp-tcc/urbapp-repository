create table if not exists public.resolution_cycles (
  id bigint generated by default as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  initiated_by uuid not null references public.profiles(id) on delete restrict,
  initiator_kind text not null default 'citizen',
  previous_status public.report_status not null,
  status text not null default 'pending',
  description text,
  confirmations_required integer not null default 3 check (confirmations_required > 0),
  rejections_required integer not null default 2 check (rejections_required > 0),
  radius_km numeric(8,3) not null default 5 check (radius_km > 0),
  cycle_duration interval not null default interval '72 hours' check (cycle_duration > interval '0 seconds'),
  initiator_cooldown interval not null default interval '24 hours' check (initiator_cooldown >= interval '0 seconds'),
  opened_at timestamptz not null default now(),
  expires_at timestamptz not null,
  closed_at timestamptz,
  constraint resolution_cycles_status_check
    check (status in ('pending', 'approved', 'rejected', 'expired', 'cancelled')),
  constraint resolution_cycles_initiator_kind_check
    check (initiator_kind in ('citizen', 'administration', 'agency', 'councilor')),
  constraint resolution_cycles_expiry_check
    check (expires_at > opened_at)
);

create unique index if not exists resolution_cycles_pending_occurrence_idx
  on public.resolution_cycles (occurrence_id)
  where status = 'pending';

create index if not exists resolution_cycles_expiry_idx
  on public.resolution_cycles (expires_at)
  where status = 'pending';

create table if not exists public.resolution_votes (
  id bigint generated by default as identity primary key,
  cycle_id bigint not null references public.resolution_cycles(id) on delete cascade,
  voter_id uuid not null references public.profiles(id) on delete restrict,
  decision text not null,
  latitude double precision not null,
  longitude double precision not null,
  distance_km numeric(10,3) not null,
  created_at timestamptz not null default now(),
  constraint resolution_votes_decision_check check (decision in ('confirm', 'reject')),
  constraint resolution_votes_coordinates_check
    check (latitude between -90 and 90 and longitude between -180 and 180),
