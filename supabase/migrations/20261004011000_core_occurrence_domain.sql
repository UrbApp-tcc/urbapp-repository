-- Mantem o app legado funcional: um post novo sem occurrence_id cria sua ocorrencia.
create or replace function public.link_new_post_to_occurrence()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  resolved_administration_id bigint;
  resolved_agency_id bigint;
  created_occurrence_id bigint;
begin
  if new.occurrence_id is not null then
    insert into public.occurrence_events (
      occurrence_id,
      actor_id,
      actor_kind,
      event_type,
      description,
      administration_id,
      agency_id,
      metadata
    )
    select
      new.occurrence_id,
      case when new.anonymity then null else new.user_id end,
      'citizen',
      'report_added',
      'Novo relato adicionado a ocorrencia.',
      occurrence.administration_id,
      occurrence.agency_id,
      jsonb_build_object('post_id', new.id)
    from public.occurrences occurrence
    where occurrence.id = new.occurrence_id;
    return new;
  end if;

  select administration.id
    into resolved_administration_id
  from public.municipal_administrations administration
  where administration.city_id = new.city_id
    and administration.ends_on is null
  order by administration.starts_on desc
  limit 1;

  select responsibility.agency_id
    into resolved_agency_id
  from public.agency_responsibilities responsibility
  where responsibility.city_id = new.city_id
    and responsibility.category_id = new.category_id
    and responsibility.ends_on is null
  order by responsibility.starts_on desc
  limit 1;

  if resolved_administration_id is null or resolved_agency_id is null then
    raise exception 'Nao foi possivel determinar gestao e orgao responsavel.';
  end if;

  insert into public.occurrences (
    city_id,
    administration_id,
    created_administration_id,
    category_id,
    agency_id,
    title,
    summary,
    latitude,
    longitude,
    street,
    neighborhood,
    status,
    created_at,
    legacy_post_id
  )
  values (
    new.city_id,
    resolved_administration_id,
    resolved_administration_id,
    new.category_id,
    resolved_agency_id,
    coalesce(nullif(trim(new.title), ''), 'Ocorrencia urbana'),
    new.description,
    new.latitude,
    new.longitude,
    new.street,
    new.neighborhood,
    'open',
    new.created_at,
    new.id
  )
  returning id into created_occurrence_id;

  update public.posts
  set occurrence_id = created_occurrence_id,
      agency_id = resolved_agency_id
  where id = new.id;

  insert into public.occurrence_agency_assignments (
    occurrence_id,
    agency_id,
    administration_id,
    reason,
    starts_at
  )
  values (
    created_occurrence_id,
    resolved_agency_id,
    resolved_administration_id,
    'Atribuicao automatica por cidade e categoria.',
    new.created_at
  );

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata,
    created_at
  )
  values
    (
      created_occurrence_id,
      new.user_id,
      'citizen',
      'occurrence_created',
      'Ocorrencia criada a partir do primeiro relato.',
      resolved_administration_id,
      resolved_agency_id,
      jsonb_build_object('post_id', new.id),
      new.created_at
    ),
    (
      created_occurrence_id,
      null,
      'system',
      'agency_assigned',
      'Ocorrencia associada automaticamente ao orgao responsavel.',
      resolved_administration_id,
      resolved_agency_id,
      jsonb_build_object('category_id', new.category_id),
      new.created_at
    );

  return new;
end;
$$;

drop trigger if exists link_post_to_occurrence on public.posts;
create trigger link_post_to_occurrence
after insert on public.posts
for each row execute function public.link_new_post_to_occurrence();

