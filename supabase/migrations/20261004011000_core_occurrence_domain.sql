create or replace function public.validate_post_status_transition()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if current_user not in ('postgres', 'service_role') then
    raise exception 'Status de reporte so pode ser alterado por uma operacao de negocio.'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

