-- UrbApp: dominio central de ocorrencias, relatos e vinculo institucional.
-- A tabela posts permanece como armazenamento dos relatos durante a migracao.

create table if not exists public.municipal_administrations (
  id bigint generated by default as identity primary key,
  city_id bigint not null references public.cities(id) on delete restrict,
  name text not null,
  mayor_name text,
  starts_on date not null,
  ends_on date,
  is_placeholder boolean not null default false,
  is_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint municipal_administrations_period_check
    check (ends_on is null or ends_on >= starts_on),
  unique (city_id, starts_on)
);

create unique index if not exists municipal_administrations_current_city_idx
  on public.municipal_administrations (city_id)
  where ends_on is null;

alter table public.public_agencies
  add column if not exists profile_status text not null default 'unclaimed',
  add column if not exists verified_at timestamptz,
  add column if not exists claimed_at timestamptz;

alter table public.public_agencies
  drop constraint if exists public_agencies_profile_status_check;

alter table public.public_agencies
  add constraint public_agencies_profile_status_check
  check (profile_status in ('unclaimed', 'verified', 'participant'));

create table if not exists public.agency_responsibilities (
  id bigint generated by default as identity primary key,
  city_id bigint not null references public.cities(id) on delete restrict,
  category_id bigint not null references public.problem_categories(id) on delete restrict,
  agency_id bigint not null references public.public_agencies(id) on delete restrict,
  starts_on date not null default current_date,
  ends_on date,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint agency_responsibilities_period_check
    check (ends_on is null or ends_on >= starts_on)
);

create unique index if not exists agency_responsibilities_current_idx
  on public.agency_responsibilities (city_id, category_id)
  where ends_on is null;

create table if not exists public.occurrences (
  id bigint generated by default as identity primary key,
  city_id bigint not null references public.cities(id) on delete restrict,
  administration_id bigint not null references public.municipal_administrations(id) on delete restrict,
  created_administration_id bigint not null references public.municipal_administrations(id) on delete restrict,
  category_id bigint not null references public.problem_categories(id) on delete restrict,
  agency_id bigint references public.public_agencies(id) on delete restrict,
  jurisdiction_type text not null default 'municipal',
  external_responsible_name text,
  title text not null,
  summary text,
  latitude double precision not null,
  longitude double precision not null,
  street text,
  neighborhood text,
  status public.report_status not null default 'open',
  previous_operational_status public.report_status,
  administrative_priority boolean not null default false,
  invalidated_at timestamptz,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  legacy_post_id bigint unique references public.posts(id) on delete set null,
  constraint occurrences_jurisdiction_check
    check (jurisdiction_type in ('municipal', 'state', 'federal', 'concessionaire', 'private', 'unknown')),
  constraint occurrences_municipal_agency_check
    check (jurisdiction_type <> 'municipal' or agency_id is not null),
  constraint occurrences_coordinates_check
    check (latitude between -90 and 90 and longitude between -180 and 180)
);

create index if not exists occurrences_city_status_created_idx
  on public.occurrences (city_id, status, created_at desc);

create index if not exists occurrences_category_location_idx
  on public.occurrences (category_id, latitude, longitude)
  where invalidated_at is null;

alter table public.posts
  add column if not exists occurrence_id bigint references public.occurrences(id) on delete restrict;

create index if not exists posts_occurrence_created_idx
  on public.posts (occurrence_id, created_at, id);

create table if not exists public.occurrence_agency_assignments (
  id bigint generated by default as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  agency_id bigint not null references public.public_agencies(id) on delete restrict,
  administration_id bigint not null references public.municipal_administrations(id) on delete restrict,
  assigned_by uuid references public.profiles(id) on delete set null,
  reason text,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  constraint occurrence_agency_assignments_period_check
    check (ends_at is null or ends_at >= starts_at)
);

create unique index if not exists occurrence_agency_assignments_current_idx
  on public.occurrence_agency_assignments (occurrence_id)
  where ends_at is null;

create table if not exists public.occurrence_events (
  id bigint generated by default as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  actor_kind text not null,
  event_type text not null,
  description text not null,
  administration_id bigint references public.municipal_administrations(id) on delete set null,
  agency_id bigint references public.public_agencies(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint occurrence_events_actor_kind_check
    check (actor_kind in ('system', 'citizen', 'administration', 'agency', 'councilor', 'moderator'))
