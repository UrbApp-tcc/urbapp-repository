-- Aproveita atribuicoes explicitas ja existentes para montar a regra inicial.
with ranked_responsibilities as (
  select
    post.city_id,
    post.category_id,
    post.agency_id,
    row_number() over (
      partition by post.city_id, post.category_id
      order by count(*) desc, post.agency_id
    ) as responsibility_rank
  from public.posts post
  where post.category_id is not null
    and post.agency_id is not null
  group by post.city_id, post.category_id, post.agency_id
)
insert into public.agency_responsibilities (city_id, category_id, agency_id, starts_on)
select city_id, category_id, agency_id, date '1900-01-01'
from ranked_responsibilities
where responsibility_rank = 1
on conflict do nothing;

-- Completa as combinacoes ainda desconhecidas com o perfil generico da cidade.
insert into public.agency_responsibilities (city_id, category_id, agency_id, starts_on)
select city.id, category.id, agency.id, date '1900-01-01'
from public.cities city
cross join public.problem_categories category
join public.public_agencies agency
  on agency.city_id = city.id
 and agency.name = 'Orgao municipal responsavel nao definido'
where not exists (
  select 1
  from public.agency_responsibilities responsibility
  where responsibility.city_id = city.id
    and responsibility.category_id = category.id
    and responsibility.ends_on is null
)
on conflict do nothing;

