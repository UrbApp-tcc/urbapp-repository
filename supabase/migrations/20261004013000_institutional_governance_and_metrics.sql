-- Governanca institucional: gestao municipal, orgaos, vereadores e indicadores.

create table if not exists public.platform_user_roles (
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null,
  granted_at timestamptz not null default now(),
  granted_by uuid references public.profiles(id) on delete set null,
  primary key (user_id, role),
  constraint platform_user_roles_role_check
    check (role in ('admin', 'moderator'))
);

create table if not exists public.administration_users (
  administration_id bigint not null references public.municipal_administrations(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'agent',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (administration_id, user_id),
  constraint administration_users_role_check
    check (role in ('manager', 'agent', 'analyst'))
);

create table if not exists public.councilor_profiles (
  id bigint generated by default as identity primary key,
  profile_id uuid not null unique references public.profiles(id) on delete cascade,
  city_id bigint not null references public.cities(id) on delete restrict,
  public_name text not null,
  party text,
  mandate_starts_on date not null,
  mandate_ends_on date not null,
  profile_status text not null default 'unclaimed',
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint councilor_profiles_period_check
    check (mandate_ends_on >= mandate_starts_on),
  constraint councilor_profiles_status_check
    check (profile_status in ('unclaimed', 'verified', 'participant'))
);

create index if not exists councilor_profiles_city_period_idx
  on public.councilor_profiles (city_id, mandate_starts_on, mandate_ends_on);

create table if not exists public.councilor_profile_requests (
  id bigint generated by default as identity primary key,
  requester_user_id uuid not null references public.profiles(id) on delete cascade,
  city_id bigint not null references public.cities(id) on delete restrict,
  public_name text not null,
  party text,
  mandate_starts_on date not null,
  mandate_ends_on date not null,
  institutional_email text not null,
  proof_summary text not null,
  proof_links text,
  status text not null default 'pending',
  review_notes text,
  reviewed_at timestamptz,
  reviewed_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint councilor_profile_requests_status_check
    check (status in ('pending', 'approved', 'rejected')),
  constraint councilor_profile_requests_period_check
    check (mandate_ends_on >= mandate_starts_on)
);

create table if not exists public.councilor_followings (
  id bigint generated by default as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  councilor_profile_id bigint not null references public.councilor_profiles(id) on delete cascade,
  status text not null default 'started',
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  constraint councilor_followings_status_check
    check (status in ('started', 'action_registered', 'awaiting_response', 'ended')),
  unique (occurrence_id, councilor_profile_id)
);

create table if not exists public.councilor_actions (
  id bigint generated by default as identity primary key,
  following_id bigint not null references public.councilor_followings(id) on delete cascade,
  action_type text not null,
  description text not null,
  evidence_storage_path text,
  created_at timestamptz not null default now(),
  constraint councilor_actions_type_check
    check (action_type in (
      'forwarding', 'request', 'charge', 'official_letter', 'agency_contact',
      'response_received', 'visit', 'verification', 'public_update',
      'possible_resolution'
    ))
);

create index if not exists councilor_actions_following_created_idx
  on public.councilor_actions (following_id, created_at);

create table if not exists public.institutional_actions (
  id bigint generated by default as identity primary key,
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  administration_id bigint references public.municipal_administrations(id) on delete restrict,
  agency_id bigint references public.public_agencies(id) on delete restrict,
  created_by uuid not null references public.profiles(id) on delete restrict,
  actor_kind text not null,
  action_type text not null,
  description text not null,
  evidence_storage_path text,
  forecast_at timestamptz,
  target_agency_id bigint references public.public_agencies(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint institutional_actions_actor_check
    check (actor_kind in ('administration', 'agency')),
  constraint institutional_actions_type_check
    check (action_type in (
      'priority', 'forwarding', 'request', 'official_position', 'forecast',
      'analysis', 'scheduled', 'in_progress', 'executed', 'conclusion'
    ))
);

create index if not exists institutional_actions_occurrence_created_idx
  on public.institutional_actions (occurrence_id, created_at);

create table if not exists public.occurrence_followers (
  occurrence_id bigint not null references public.occurrences(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (occurrence_id, user_id)
);

create or replace function public.is_platform_admin(target_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(auth.role(), '') = 'service_role'
    or exists (
      select 1
      from public.platform_user_roles role
      where role.user_id = target_user_id
        and role.role in ('admin', 'moderator')
    );
$$;

create or replace function public.register_institutional_action(
  target_occurrence_id bigint,
  institutional_action_type text,
  action_description text,
  action_target_agency_id bigint default null,
  action_forecast_at timestamptz default null,
  evidence_storage_path text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  target_occurrence public.occurrences%rowtype;
  resolved_actor_kind text;
  created_action_id bigint;
  target_status public.report_status;
begin
  if current_user_id is null then
    raise exception 'Usuario autenticado e obrigatorio.' using errcode = '42501';
  end if;

  if institutional_action_type not in (
    'priority', 'forwarding', 'request', 'official_position', 'forecast',
    'analysis', 'scheduled', 'in_progress', 'executed', 'conclusion'
  ) then
    raise exception 'Tipo de acao institucional invalido.';
  end if;

  if char_length(trim(coalesce(action_description, ''))) < 3 then
    raise exception 'Descreva a acao institucional.';
  end if;

  select * into target_occurrence
  from public.occurrences occurrence
  where occurrence.id = target_occurrence_id
    and occurrence.invalidated_at is null
  for update;

  if not found then
    raise exception 'Ocorrencia nao encontrada.';
  end if;

  if exists (
    select 1
    from public.administration_users member
    where member.administration_id = target_occurrence.administration_id
      and member.user_id = current_user_id
      and member.is_active = true
  ) then
    resolved_actor_kind := 'administration';
  elsif exists (
    select 1
    from public.agency_users member
    where member.agency_id = target_occurrence.agency_id
      and member.user_id = current_user_id
      and member.is_active = true
  ) then
    resolved_actor_kind := 'agency';
  else
    raise exception 'Usuario nao representa a gestao ou o orgao responsavel.' using errcode = '42501';
  end if;

  if institutional_action_type in ('priority', 'forwarding', 'request')
     and resolved_actor_kind <> 'administration' then
    raise exception 'Esta acao e exclusiva da gestao municipal.' using errcode = '42501';
  end if;

  if institutional_action_type = 'forwarding' then
    if action_target_agency_id is null or not exists (
      select 1
      from public.public_agencies agency
      where agency.id = action_target_agency_id
        and agency.city_id = target_occurrence.city_id
    ) then
      raise exception 'Selecione um orgao valido da mesma cidade.';
    end if;

    update public.occurrence_agency_assignments
    set ends_at = now()
    where occurrence_id = target_occurrence.id
      and ends_at is null;

    insert into public.occurrence_agency_assignments (
      occurrence_id,
      agency_id,
      administration_id,
      assigned_by,
      reason
    )
    values (
      target_occurrence.id,
      action_target_agency_id,
      target_occurrence.administration_id,
      current_user_id,
      trim(action_description)
    );

    update public.occurrences
    set agency_id = action_target_agency_id
    where id = target_occurrence.id;

    update public.posts
    set agency_id = action_target_agency_id
    where occurrence_id = target_occurrence.id;
  end if;

  if institutional_action_type = 'priority' then
    update public.occurrences
    set administrative_priority = true
    where id = target_occurrence.id;
  elsif institutional_action_type = 'analysis' then
    target_status := 'in_analysis';
  elsif institutional_action_type in ('scheduled', 'in_progress', 'executed') then
    target_status := 'in_progress';
  end if;

  if target_status is not null
     and target_occurrence.status in ('open', 'in_analysis', 'in_progress', 'reopened')
     and target_occurrence.status is distinct from target_status then
    update public.occurrences
    set status = target_status
    where id = target_occurrence.id;

    perform public.sync_occurrence_status_to_posts(
      target_occurrence.id,
      target_status,
      current_user_id,
      trim(action_description)
    );
  end if;

  insert into public.institutional_actions (
    occurrence_id,
    administration_id,
    agency_id,
    created_by,
    actor_kind,
    action_type,
    description,
    evidence_storage_path,
    forecast_at,
    target_agency_id
  )
  values (
    target_occurrence.id,
    target_occurrence.administration_id,
    case when resolved_actor_kind = 'agency' then target_occurrence.agency_id else null end,
    current_user_id,
    resolved_actor_kind,
    institutional_action_type,
    trim(action_description),
    nullif(trim(coalesce(evidence_storage_path, '')), ''),
    action_forecast_at,
    action_target_agency_id
  )
  returning id into created_action_id;

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata
  )
  values (
    target_occurrence.id,
    current_user_id,
    resolved_actor_kind,
    'institutional_' || institutional_action_type,
    trim(action_description),
    target_occurrence.administration_id,
    coalesce(action_target_agency_id, target_occurrence.agency_id),
    jsonb_build_object(
      'institutional_action_id', created_action_id,
      'forecast_at', action_forecast_at,
      'evidence_storage_path', nullif(trim(coalesce(evidence_storage_path, '')), '')
    )
  );

  if institutional_action_type = 'conclusion' then
    perform public.open_resolution_cycle(
      target_occurrence.id,
      trim(action_description),
      resolved_actor_kind
    );
  end if;

  return created_action_id;
end;
$$;

create or replace function public.start_councilor_following(target_occurrence_id bigint)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  resolved_councilor_id bigint;
  created_following_id bigint;
  target_occurrence public.occurrences%rowtype;
begin
  if current_user_id is null then
    raise exception 'Usuario autenticado e obrigatorio.' using errcode = '42501';
  end if;

  select * into target_occurrence
  from public.occurrences occurrence
  where occurrence.id = target_occurrence_id
    and occurrence.invalidated_at is null;

  if not found then
    raise exception 'Ocorrencia nao encontrada.';
  end if;

  select councilor.id into resolved_councilor_id
  from public.councilor_profiles councilor
  where councilor.profile_id = current_user_id
    and councilor.city_id = target_occurrence.city_id
    and councilor.profile_status in ('verified', 'participant')
    and current_date between councilor.mandate_starts_on and councilor.mandate_ends_on;

  if resolved_councilor_id is null then
    raise exception 'Perfil de vereador verificado e obrigatorio.' using errcode = '42501';
  end if;

  insert into public.councilor_followings (
    occurrence_id,
    councilor_profile_id
  )
  values (target_occurrence.id, resolved_councilor_id)
  on conflict (occurrence_id, councilor_profile_id) do update
    set ended_at = null,
        status = 'started'
  returning id into created_following_id;

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata
  )
  values (
    target_occurrence.id,
    current_user_id,
    'councilor',
    'councilor_following_started',
    'Vereador iniciou o acompanhamento da demanda.',
    target_occurrence.administration_id,
    target_occurrence.agency_id,
    jsonb_build_object('following_id', created_following_id)
  );

  return created_following_id;
end;
$$;

create or replace function public.register_councilor_action(
  target_following_id bigint,
  councilor_action_type text,
  action_description text,
  evidence_storage_path text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  target_following public.councilor_followings%rowtype;
  target_occurrence public.occurrences%rowtype;
  created_action_id bigint;
begin
  select following.* into target_following
  from public.councilor_followings following
  join public.councilor_profiles councilor
    on councilor.id = following.councilor_profile_id
  where following.id = target_following_id
    and councilor.profile_id = current_user_id
    and councilor.profile_status in ('verified', 'participant')
  for update of following;

  if not found then
    raise exception 'Acompanhamento nao encontrado ou sem permissao.' using errcode = '42501';
  end if;

  if char_length(trim(coalesce(action_description, ''))) < 3 then
    raise exception 'Descreva a acao de acompanhamento.';
  end if;

  select * into target_occurrence
  from public.occurrences occurrence
  where occurrence.id = target_following.occurrence_id;

  insert into public.councilor_actions (
    following_id,
    action_type,
    description,
    evidence_storage_path
  )
  values (
    target_following.id,
    councilor_action_type,
    trim(action_description),
    nullif(trim(coalesce(evidence_storage_path, '')), '')
  )
  returning id into created_action_id;

  update public.councilor_followings
  set status = case
        when councilor_action_type = 'response_received' then 'awaiting_response'
        else 'action_registered'
      end
  where id = target_following.id;

  insert into public.occurrence_events (
    occurrence_id,
    actor_id,
    actor_kind,
    event_type,
    description,
    administration_id,
    agency_id,
    metadata
  )
  values (
    target_occurrence.id,
    current_user_id,
    'councilor',
    'councilor_' || councilor_action_type,
    trim(action_description),
    target_occurrence.administration_id,
    target_occurrence.agency_id,
    jsonb_build_object(
      'following_id', target_following.id,
      'councilor_action_id', created_action_id,
      'evidence_storage_path', nullif(trim(coalesce(evidence_storage_path, '')), '')
    )
  );

  if councilor_action_type = 'possible_resolution' then
    perform public.open_resolution_cycle(
      target_occurrence.id,
      trim(action_description),
      'councilor'
    );
  end if;

  return created_action_id;
end;
$$;

create or replace function public.rollover_municipal_administration(
  target_city_id bigint,
  administration_name text,
  mayor_name text,
  starts_on date,
  ends_on date default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  previous_administration_id bigint;
  new_administration_id bigint;
  inherited_occurrence record;
begin
  if not public.is_platform_admin(current_user_id) then
    raise exception 'Apenas administradores do UrbApp podem alterar a gestao.' using errcode = '42501';
  end if;

  if $1 is null or not exists (
    select 1 from public.cities city where city.id = $1
  ) then
    raise exception 'Cidade nao encontrada.';
  end if;

  if char_length(trim(coalesce($2, ''))) < 3 then
    raise exception 'Informe o nome da nova gestao.';
  end if;

  if $4 is null or ($5 is not null and $5 < $4) then
    raise exception 'Periodo da gestao invalido.';
  end if;

  select administration.id into previous_administration_id
  from public.municipal_administrations as administration
  where administration.city_id = $1
    and administration.ends_on is null
  for update;

  if previous_administration_id is not null then
    update public.municipal_administrations
    set ends_on = $4 - 1
    where id = previous_administration_id;
  end if;

  insert into public.municipal_administrations (
    city_id,
    name,
    mayor_name,
    starts_on,
    ends_on,
    is_placeholder,
    is_verified
  )
  values (
    $1,
    trim($2),
    nullif(trim(coalesce($3, '')), ''),
    $4,
    $5,
    false,
    true
  )
  returning id into new_administration_id;

  for inherited_occurrence in
    update public.occurrences
    set administration_id = new_administration_id
    where occurrences.city_id = $1
      and occurrences.status in ('open', 'in_analysis', 'in_progress', 'awaiting_validation', 'reopened')
    returning id, agency_id
  loop
    insert into public.occurrence_events (
      occurrence_id,
      actor_id,
      actor_kind,
      event_type,
      description,
      administration_id,
      agency_id,
      metadata
    )
    values (
      inherited_occurrence.id,
      current_user_id,
      'moderator',
      'administration_changed',
      'Ocorrencia herdada pela nova gestao municipal.',
      new_administration_id,
      inherited_occurrence.agency_id,
      jsonb_build_object('previous_administration_id', previous_administration_id)
    );
  end loop;

  return new_administration_id;
end;
$$;

-- Notificacoes de dominio para autores e seguidores da ocorrencia.
create or replace function public.notify_occurrence_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recipient record;
  notification_title text;
begin
  if new.event_type in ('occurrence_created', 'report_added') then
    return new;
  end if;

  notification_title := case
    when new.event_type = 'validation_opened' then 'Validacao comunitaria aberta'
    when new.event_type = 'resolution_confirmed' then 'Ocorrencia resolvida'
    when new.event_type = 'validation_rejected' then 'Solucao nao confirmada'
    when new.event_type = 'occurrence_reopened' then 'Ocorrencia reaberta'
    when new.event_type = 'institutional_priority' then 'Prioridade reconhecida pela gestao'
    when new.actor_kind = 'agency' then 'Atualizacao do orgao responsavel'
    when new.actor_kind = 'administration' then 'Atualizacao da gestao municipal'
    when new.actor_kind = 'councilor' then 'Atualizacao de acompanhamento'
    else 'Atualizacao da ocorrencia'
  end;

  for recipient in
    select distinct recipient_id
    from (
      select post.user_id as recipient_id
      from public.posts post
      where post.occurrence_id = new.occurrence_id
      union
      select follower.user_id
      from public.occurrence_followers follower
      where follower.occurrence_id = new.occurrence_id
    ) recipients
    where recipient_id is not null
      and recipient_id is distinct from new.actor_id
  loop
    perform public.notify_user(
      recipient.recipient_id,
      'occurrence_event',
      notification_title,
      new.description,
      jsonb_build_object(
        'occurrence_id', new.occurrence_id,
        'event_id', new.id,
        'event_type', new.event_type
      )
    );
  end loop;

  return new;
end;
$$;

drop trigger if exists notify_on_occurrence_event on public.occurrence_events;
create trigger notify_on_occurrence_event
after insert on public.occurrence_events
for each row execute function public.notify_occurrence_event();

-- Indicadores sempre contam ocorrencias unicas, nunca relatos individuais.
create or replace view public.city_occurrence_metrics
with (security_invoker = true)
as
select
  city.id as city_id,
  city.name as city_name,
  count(occurrence.id) filter (where occurrence.invalidated_at is null) as total_occurrences,
  count(occurrence.id) filter (where occurrence.status = 'completed' and occurrence.invalidated_at is null) as resolved_occurrences,
  count(occurrence.id) filter (where occurrence.status = 'open' and occurrence.invalidated_at is null) as open_occurrences,
  count(occurrence.id) filter (where occurrence.status in ('in_analysis', 'in_progress', 'reopened') and occurrence.invalidated_at is null) as active_occurrences,
  count(occurrence.id) filter (where occurrence.status = 'awaiting_validation' and occurrence.invalidated_at is null) as awaiting_validation_occurrences,
  round(
    100.0 * count(occurrence.id) filter (where occurrence.status = 'completed' and occurrence.invalidated_at is null)
    / nullif(count(occurrence.id) filter (where occurrence.invalidated_at is null), 0),
    2
  ) as resolution_rate,
  avg(occurrence.resolved_at - occurrence.created_at)
    filter (where occurrence.status = 'completed' and occurrence.invalidated_at is null) as average_resolution_time
from public.cities city
left join public.occurrences occurrence on occurrence.city_id = city.id
group by city.id;

create or replace view public.administration_occurrence_metrics
with (security_invoker = true)
as
select
  administration.id as administration_id,
  administration.city_id,
  administration.name,
  administration.starts_on,
  administration.ends_on,
  count(distinct occurrence.id) filter (
    where occurrence.created_administration_id = administration.id
      and occurrence.invalidated_at is null
  ) as registered_during_period,
  count(distinct occurrence.id) filter (
    where occurrence.administration_id = administration.id
      and occurrence.created_administration_id <> administration.id
      and occurrence.invalidated_at is null
  ) as inherited_occurrences,
  count(distinct event.occurrence_id) filter (
    where event.event_type = 'resolution_confirmed'
      and event.administration_id = administration.id
  ) as resolved_during_period,
  count(distinct action.occurrence_id) filter (
    where action.action_type = 'priority'
  ) as prioritized_occurrences,
  count(distinct action.occurrence_id) filter (
    where action.action_type = 'official_position'
  ) as officially_answered_occurrences
from public.municipal_administrations administration
left join public.occurrences occurrence
  on occurrence.created_administration_id = administration.id
  or occurrence.administration_id = administration.id
left join public.occurrence_events event
  on event.occurrence_id = occurrence.id
 and event.administration_id = administration.id
left join public.institutional_actions action
  on action.occurrence_id = occurrence.id
 and action.administration_id = administration.id
group by administration.id;

create or replace view public.agency_occurrence_metrics
with (security_invoker = true)
as
select
  agency.id as agency_id,
  agency.city_id,
  agency.name,
  agency.profile_status,
  count(distinct occurrence.id) filter (where occurrence.invalidated_at is null) as assigned_occurrences,
  count(distinct occurrence.id) filter (
    where occurrence.status = 'completed' and occurrence.invalidated_at is null
  ) as resolved_occurrences,
  count(distinct action.id) as official_actions,
  min(action.created_at) as first_recorded_action_at
from public.public_agencies agency
left join public.occurrence_agency_assignments assignment on assignment.agency_id = agency.id
left join public.occurrences occurrence on occurrence.id = assignment.occurrence_id
left join public.institutional_actions action
  on action.occurrence_id = occurrence.id
 and action.agency_id = agency.id
group by agency.id;

create or replace view public.councilor_activity_metrics
with (security_invoker = true)
as
select
  councilor.id as councilor_profile_id,
  councilor.profile_id,
  councilor.city_id,
  councilor.public_name,
  count(distinct following.id) as followed_demands,
  count(distinct action.id) as registered_actions,
  count(distinct following.id) filter (
    where exists (
      select 1
      from public.councilor_actions concrete_action
      join public.occurrence_events resolution_event
        on resolution_event.occurrence_id = following.occurrence_id
       and resolution_event.event_type = 'resolution_confirmed'
       and resolution_event.created_at > concrete_action.created_at
      where concrete_action.following_id = following.id
    )
  ) as followed_demands_that_reached_resolution
from public.councilor_profiles councilor
left join public.councilor_followings following
  on following.councilor_profile_id = councilor.id
left join public.councilor_actions action
  on action.following_id = following.id
group by councilor.id;

